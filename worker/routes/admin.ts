admin.post("/api/admin/taxonomy", async (c) => {
  const me = await requireStaff(c, "taxonomy.manage");
  const input = await body(c, z.object({ kind: z.enum(["looking_for", "gender", "orientation"]), slug: z.string().trim().toLowerCase().regex(/^[a-z0-9_]{2,40}$/), label: z.string().trim().min(2).max(60), active: z.boolean().default(true) }));
  const db = c.get("db");
  const [existing] = await db.select().from(schema.taxonomy).where(and(eq(schema.taxonomy.kind, input.kind), eq(schema.taxonomy.slug, input.slug)));
  if (existing) await db.update(schema.taxonomy).set({ label: input.label, active: input.active }).where(eq(schema.taxonomy.id, existing.id));
  else {
    const [{ max } = { max: -1 }] = await db.select({ max: sql<number>`coalesce(max(${schema.taxonomy.position}), -1)` }).from(schema.taxonomy).where(eq(schema.taxonomy.kind, input.kind));
    await db.insert(schema.taxonomy).values({ id: newId("tax"), kind: input.kind, slug: input.slug, label: input.label, position: max + 1, active: input.active });
  }
  await audit(db, me.actor, "taxonomy.upsert", "taxonomy", `${input.kind}:${input.slug}`, { label: input.label, active: input.active }, c.get("now"));
  return c.json({ ok: true });
});

