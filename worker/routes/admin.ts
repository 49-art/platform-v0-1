admin.post("/api/admin/le/:id", async (c) => {
  const me = await requireStaff(c, "le.desk");
  const input = await body(c, z.object({
    action: z.enum(["basis_checked", "preserve", "disclose", "refuse", "close"]), note: z.string().trim().max(4000).default(""), preserveDays: z.number().int().min(1).max(3650).default(90),
  }));
  const db = c.get("db");
  const now = c.get("now");
  const [req] = await db.select().from(schema.leRequests).where(eq(schema.leRequests.id, c.req.param("id")));
  if (!req) throw notFound();
  if (input.action === "disclose" && !req.legalBasisChecked && !req.emergency) throw bad("basis_required", "Record the legal-basis check before any disclosure (emergency threat-to-life requests excepted).");
  const set: Partial<typeof schema.leRequests.$inferInsert> = { updatedAt: now };
  if (input.action === "basis_checked") set.legalBasisChecked = true;
  if (input.action === "preserve") {
    if (!req.subjectUserId) throw bad("no_subject", "Add the member's id to preserve their records.");
    set.status = "preserved";
    set.preservationUntil = now + input.preserveDays * DAY;
    // A legal hold stops scheduled erasure from destroying the records (spec 3 deletion exceptions).
    await db.insert(schema.legalHolds).values({ userId: req.subjectUserId, leRequestId: req.id, until: now + input.preserveDays * DAY, createdAt: now }).onConflictDoUpdate({ target: [schema.legalHolds.userId, schema.legalHolds.leRequestId], set: { until: now + input.preserveDays * DAY } });
  }
  if (input.action === "disclose") { set.status = "disclosed"; set.disclosureNote = input.note; }
  if (input.action === "refuse") { set.status = "refused"; set.disclosureNote = input.note; }
  if (input.action === "close") set.status = "closed";
  await db.update(schema.leRequests).set(set).where(eq(schema.leRequests.id, req.id));
  await audit(db, me.actor, `le.${input.action}`, "le_request", req.id, { note: input.note, subjectUserId: req.subjectUserId }, now);
  return c.json({ ok: true });
});

