/** A ban or suspension takes effect on live connections at once (spec 6 "Moderation actions"). */
async function afterStandingChange(env: Env, userId: string) {
  const db = makeDb(env.DB);
  const [user] = await db.select({ status: schema.users.status }).from(schema.users).where(eq(schema.users.id, userId));
  if (!user) return;
  const hub = env.USER_HUB.get(env.USER_HUB.idFromName(userId));
  if (user.status === "suspended" || user.status === "banned") {
    await hub.closeAll(user.status);
    const convs = await db.select({ id: schema.conversations.id }).from(schema.conversations).where(or(eq(schema.conversations.userA, userId), eq(schema.conversations.userB, userId)));
    for (const conv of convs) await env.CHAT_ROOM.get(env.CHAT_ROOM.idFromName(conv.id)).freeze(`member_${user.status}`);
  } else {
    await hub.push({ type: "standing", status: user.status });
  }
  await dispatch(env, { kind: "notify", userId, reason: "moderation" });
}

