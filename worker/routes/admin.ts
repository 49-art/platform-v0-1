admin.post("/api/admin/staff", async (c) => {
  const me = await requireStaff(c, "staff.manage");
  const input = await body(c, z.object({ email: z.string().trim().toLowerCase().email(), name: z.string().trim().max(60).default(""), role: z.enum(["moderator", "senior_moderator", "ts_lead", "admin", "agency_staff"]) }));
  const db = c.get("db");
  const [existing] = await db.select().from(schema.staff).where(eq(schema.staff.email, input.email));
  if (existing) await db.update(schema.staff).set({ role: input.role, name: input.name || existing.name, active: true }).where(eq(schema.staff.id, existing.id));
  else await db.insert(schema.staff).values({ id: newId("stf"), email: input.email, name: input.name, role: input.role, createdAt: c.get("now") });
  await audit(db, me.actor, "staff.upsert", "staff", input.email, { role: input.role }, c.get("now"));
  return c.json({ ok: true });
});

