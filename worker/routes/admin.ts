async function launchWarnings(c: Context<AppEnv>) {
  const w: string[] = [];
  if (isSample(c.env)) w.push("SAMPLE MODE is on. Age and ID checks are simulated, emails are not sent, and links are shown on screen.");
  if (await usingGeneratedSecrets(c.env)) w.push("Encryption keys were generated by the app and are stored in the database. Set APP_SECRET and the other secrets in Cloudflare before any real member data is stored.");
  if (c.env.TURNSTILE_SITE_KEY?.startsWith("1x0000")) w.push("Turnstile is using Cloudflare's always-pass TEST keys, so the bot gate lets everyone through.");
  if (c.env.PASSWORD_ALGO === "pbkdf2") w.push("Passwords use the free-plan PBKDF2 setting. The Workers Paid plan restores Argon2id.");
  if (c.env.AGE_PROVIDER === "mock" || c.env.IDV_PROVIDER === "mock") w.push("No real age or ID provider is connected (open decision: Yoti, Persona, Onfido or Veriff).");
  if (c.env.SCAN_PROVIDER === "mock") w.push("No real image scanner is connected. Every photo still goes to a human in the pre-moderation queue.");
  return w;
}

