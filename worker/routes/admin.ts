admin.post("/api/admin/premod/:id", async (c) => {
  const staff = await requireStaff(c, "queue.premod");
  const input = await body(c, z.object({ decision: z.enum(["approve", "reject", "escalate"]), reasonCode: z.string().optional() }));
  const db = c.get("db");
  const result = await decideModeration(c.env, db, staff.actor, c.req.param("id"), input.decision, input.reasonCode, c.get("now"));
  for (const key of result.r2KeysToDelete) await removeMedia(c.env, key);
  if (result.deliverChatPhotoId) {
    const [photo] = await db.select().from(schema.photos).where(eq(schema.photos.id, result.deliverChatPhotoId));
    if (photo?.conversationId) await c.env.CHAT_ROOM.get(c.env.CHAT_ROOM.idFromName(photo.conversationId)).postImage(photo.userId, photo.id, photo.explicit);
  }
  if (result.disconnectUserId) await afterStandingChange(c.env, result.disconnectUserId);
  else await dispatch(c.env, { kind: "notify", userId: result.notifyUserId, reason: "moderation" });
  return c.json({ ok: true });
});

/* ── Report queue (spec 8: priority by reason, age and reporter trust; assign, escalate, merge; reporter told the outcome) ── */

admin.get("/api/admin/reports", async (c) => {
  const staff = await requireStaff(c, "queue.reports");
  const db = c.get("db");
  const status = c.req.query("status") === "resolved" ? ["resolved"] : ["open", "assigned", "escalated"];
  const rows = await db.select().from(schema.reports).where(inArray(schema.reports.status, status as any)).orderBy(asc(schema.reports.priority), asc(schema.reports.createdAt)).limit(100);
  const out = [];
  for (const r of rows) {
    if (r.status === "escalated" && !can(staff.role, "escalation.handle") && r.priority === 0 && ["csam", "threat", "underage"].includes(r.reason)) {
      // Moderators see that an escalation exists but the Trust and safety lead handles it.
      out.push({ id: r.id, reason: r.reason, priority: r.priority, status: r.status, createdAt: r.createdAt, restricted: true });
      continue;
    }
    const [subject] = await db.select({ displayName: schema.profiles.displayName }).from(schema.profiles).where(eq(schema.profiles.userId, r.subjectUserId));
    const [u] = await db.select({ status: schema.users.status, risk: schema.users.riskScore }).from(schema.users).where(eq(schema.users.id, r.subjectUserId));
    const merged = await db.select({ id: schema.reports.id }).from(schema.reports).where(eq(schema.reports.mergedInto, r.id));
    out.push({
      id: r.id, reason: r.reason, reasonLabel: REPORT_REASONS[r.reason as keyof typeof REPORT_REASONS]?.label ?? r.reason, priority: r.priority, status: r.status,
      detail: r.detail, createdAt: r.createdAt, assignedTo: r.assignedTo, subjectUserId: r.subjectUserId, subject: { name: subject?.displayName ?? "(no profile)", status: u?.status, riskScore: u?.risk ?? 0 },
      conversationId: r.conversationId, reporterId: r.reporterId, duplicates: merged.length, outcome: r.outcome, outcomeNote: r.outcomeNote,
    });
  }
  return c.json({ reports: out, reasons: Object.values(REASON_CODES).map((x) => ({ code: x.code, label: x.label, zeroTolerance: x.zeroTolerance })) });
});

