admin.get("/api/admin/dashboard", async (c) => {
  await requireStaff(c, "dashboards.view");
  const db = c.get("db");
  const now = c.get("now");
  const n = async (q: Promise<{ n: number }[]>) => (await q)[0]?.n ?? 0;
  const count = sql<number>`count(*)`.as("n");
  const since = now - 30 * DAY;
  const realUsers = sql`${schema.users.email} is null or ${schema.users.email} not like ${"%@sample.invalid"}`;
  const ageAll = await n(db.select({ n: count }).from(schema.ageChecks).where(and(gt(schema.ageChecks.createdAt, since), sql`${schema.ageChecks.status} != 'pending'`, sql`${schema.ageChecks.provider} != 'sample'`)));
  const agePass = await n(db.select({ n: count }).from(schema.ageChecks).where(and(gt(schema.ageChecks.createdAt, since), eq(schema.ageChecks.status, "passed"), sql`${schema.ageChecks.provider} != 'sample'`)));
  const idvAll = await n(db.select({ n: count }).from(schema.idVerifications).where(and(gt(schema.idVerifications.createdAt, since), sql`${schema.idVerifications.status} != 'pending'`, sql`${schema.idVerifications.provider} != 'sample'`)));
  const idvPass = await n(db.select({ n: count }).from(schema.idVerifications).where(and(gt(schema.idVerifications.createdAt, since), eq(schema.idVerifications.status, "passed"), sql`${schema.idVerifications.provider} != 'sample'`)));
  const group = async (table: any, col: any, where?: any) => (await db.select({ k: col, n: count }).from(table).where(where).groupBy(col)) as { k: string; n: number }[];
  return c.json({
    signups: { total: await n(db.select({ n: count }).from(schema.users).where(realUsers)), last7d: await n(db.select({ n: count }).from(schema.users).where(and(realUsers, gt(schema.users.createdAt, now - 7 * DAY)))) },
    ageCheck: { decided: ageAll, passRate: ageAll ? Math.round((agePass / ageAll) * 100) : null },
    verification: { decided: idvAll, passRate: idvAll ? Math.round((idvPass / idvAll) * 100) : null },
    queue: { pending: await n(db.select({ n: count }).from(schema.modQueue).where(eq(schema.modQueue.status, "pending"))), overdue: await n(db.select({ n: count }).from(schema.modQueue).where(and(eq(schema.modQueue.status, "pending"), lt(schema.modQueue.slaDueAt, now)))) },
    reportsByReason: await group(schema.reports, schema.reports.reason, inArray(schema.reports.status, ["open", "assigned", "escalated"])),
    actionsByKind: await group(schema.enforcementActions, schema.enforcementActions.kind, gt(schema.enforcementActions.createdAt, since)),
    botBlocks: await group(schema.botEvents, schema.botEvents.kind, gt(schema.botEvents.createdAt, since)),
    activeChats: await n(db.select({ n: count }).from(schema.conversations).where(and(eq(schema.conversations.status, "open"), gt(schema.conversations.lastMessageAt, now - 7 * DAY)))),
    datesArranged: await n(db.select({ n: count }).from(schema.dates).where(eq(schema.dates.status, "accepted"))),
    safetyAlerts: { sos: await n(db.select({ n: count }).from(schema.dateSafety).where(isNotNull(schema.dateSafety.sosAt))), missedCheckins: await n(db.select({ n: count }).from(schema.dateSafety).where(isNotNull(schema.dateSafety.alertedAt))) },
    sampleMembers: isSample(c.env) ? await countSampleMembers(db) : null,
  });
});

/* ── Pre-moderation queue (spec 8: auto-scores, approve / reject with reason, SLA timers) ── */

admin.get("/api/admin/premod", async (c) => {
  const staff = await requireStaff(c, "queue.premod");
  const db = c.get("db");
  const items = await db.select().from(schema.modQueue).where(eq(schema.modQueue.status, "pending")).orderBy(asc(schema.modQueue.slaDueAt)).limit(50);
  const out = [];
  for (const item of items) {
    if (item.kind === "ban_evasion" && !can(staff.role, "ban_evasion.review")) continue;
    const [profile] = await db.select().from(schema.profiles).where(eq(schema.profiles.userId, item.userId));
    const photos = item.kind === "photo"
      ? await db.select().from(schema.photos).where(eq(schema.photos.id, item.refId))
      : await db.select().from(schema.photos).where(and(eq(schema.photos.userId, item.userId), eq(schema.photos.purpose, "profile"), inArray(schema.photos.status, ["pending", "approved"])));
    out.push({
      id: item.id, kind: item.kind, userId: item.userId, scores: JSON.parse(item.scores || "{}"), slaDueAt: item.slaDueAt, createdAt: item.createdAt,
      profile: profile ? { displayName: profile.displayName, bio: profile.bio, birthYear: profile.birthYear, lookingFor: profile.lookingFor, area: profile.areaLabel, countryOfOrigin: profile.countryOfOrigin, status: profile.status } : null,
      photos: photos.filter((p) => p.status !== "quarantined").map((p) => ({ id: p.id, status: p.status, purpose: p.purpose, scores: p.scores ? JSON.parse(p.scores) : null, url: `/api/admin/media/${p.id}` })),
    });
  }
  return c.json({ items: out, reasons: Object.values(REASON_CODES).map((r) => ({ code: r.code, label: r.label })) });
});

