admin.post("/api/admin/reports/:id/merge", async (c) => {
  const staff = await requireStaff(c, "queue.reports");
  const { into } = await body(c, z.object({ into: z.string() }));
  const db = c.get("db");
  const id = c.req.param("id");
  if (id === into) throw bad("same", "A report cannot be merged into itself.");
  const [a] = await db.select().from(schema.reports).where(eq(schema.reports.id, id));
  const [b] = await db.select().from(schema.reports).where(eq(schema.reports.id, into));
  if (!a || !b) throw notFound();
  if (a.subjectUserId !== b.subjectUserId) throw bad("different_subject", "Only reports about the same member can be merged.");
  await db.update(schema.reports).set({ status: "merged", mergedInto: into }).where(eq(schema.reports.id, id));
  await audit(db, staff.actor, "report.merge", "report", id, { into }, c.get("now"));
  return c.json({ ok: true });
});

admin.post("/api/admin/reports/:id/resolve", async (c) => {
  const staff = await requireStaff(c, "queue.reports");
  const input = await body(c, z.object({
    outcome: z.enum(["action_taken", "no_action", "escalated"]), note: z.string().trim().max(2000).default(""),
    action: z.object({ kind: z.enum(["warn", "restrict", "suspend", "ban"]), reasonCode: z.string(), durationDays: z.number().int().min(1).max(3650).optional() }).optional(),
  }));
  const db = c.get("db");
  const [report] = await db.select().from(schema.reports).where(eq(schema.reports.id, c.req.param("id")));
  if (!report) throw notFound();
  if (input.outcome === "action_taken") {
    if (!input.action) throw bad("action_required", "Choose the action you are taking.");
    await applyEnforcement(c.env, db, staff.actor, { userId: report.subjectUserId, kind: input.action.kind, reasonCode: input.action.reasonCode, note: input.note, reportId: report.id, durationMs: input.action.durationDays ? input.action.durationDays * DAY : undefined }, c.get("now"));
    await afterStandingChange(c.env, report.subjectUserId);
  }
  await resolveReport(db, staff.actor, report.id, input.outcome, input.note, c.get("now"));
  if (report.reporterId !== "system") await dispatch(c.env, { kind: "notify", userId: report.reporterId, reason: "report" });
  return c.json({ ok: true });
});

