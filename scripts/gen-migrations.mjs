// Embeds migrations/*.sql into worker/generated/migrations.ts so the Worker can bring its own D1 database up to date
// on first use (decision D-020). Runs before every build; the output is committed so tests and dry-runs work too.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../migrations/", import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const entries = files.map((name) => {
  const sql = readFileSync(join(dir, name), "utf8");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.replace(/^\s*--.*$/gm, "").trim())
    .filter(Boolean);
  return { name, statements };
});
const out = `// GENERATED by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(entries, null, 2)};\n`;
mkdirSync(new URL("../worker/generated/", import.meta.url).pathname, { recursive: true });
writeFileSync(new URL("../worker/generated/migrations.ts", import.meta.url).pathname, out);
console.log(`migrations: ${files.length} files, ${entries.reduce((n, e) => n + e.statements.length, 0)} statements`);
